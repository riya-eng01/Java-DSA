public class AssignmentOperator {
    public static void main(String args[]) {
        // Assignment Operators

        // Assign value from right to left '='
        int a = 10;

        // Plus equals to
        a += 5; // 10 + 5 = 15
        System.out.println(a);

        // Minus equals to
        a -= 5; // 15 - 5 = 10
        System.out.println(a); 

        // Multiply equals to
        a *= 2; // 10 * 2 = 20
        System.out.println(a);

        // divide equals to 
        a /= 5; // 20 / 5 = 4
        System.out.println(a);

        // Modulo equals to
        a %= 2; // 4 % 2 = 0
        System.out.println(a);

    }
}