public class Arithmetic {
    public static void main(String args[]) {
        // Binary Operators
        int a = 10;
        int b = 5;

        System.out.println("Add = " + (a+b));
        System.out.println("Sub = " + (a-b));
        System.out.println("prod = " + (a*b));
        System.out.println("div = " + (a/b));
        System.out.println("rem = " + (a%b));
    }
}