public class Relational {
    public static void main(String args[]) {
        // Relational Operators
        int a = 10;
        int b = 5;

        System.out.println(a > b); // Output-> true
        System.out.println(a < b); // false
        System.out.println(a == b); // false
        System.out.println(a >= b); // true
        System.out.println(a <= b); // false
        System.out.println(a != b); // true

    }
}